import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { splitHelp } from '../command-argv.ts';
import {
  resolveProjectContext,
  surfaceApiError,
  takeFlagBool,
  takeFlagValue,
  takeFlagValues,
  fail,
  missing,
} from '../command-helpers.ts';
import { C, help, status } from '../style.ts';
import type { ProjectSecret, ProjectSecretsResponse } from '../api/types.ts';

const HELP = help`Usage: kortix env <subcommand> [options]

Bulk transfer secrets between a local .env file and the cloud.

Subcommands:
  pull [--out <path>]              Write each cloud secret as a line in
                                   the dotenv file (defaults to ./.env).
                                   VALUES ARE NOT EXPOSED — we only have
                                   names. Each line is "NAME=" so you can
                                   fill in locally.
  push --from <path>               Upload every NAME=VALUE in the file
                                   as a workspace secret.
    --names                        Print the names in the file, never a
                                   value, and upload nothing. --json.
    --only <A,B>                   Upload only these names.
    --exclude <A,B>                Upload every name but these.
                                   A dotenvx "encrypted:" value is never
                                   uploaded: decrypt it first.

Global options:
  --workspace <id>   Operate on this workspace id (default: linked).
  --force            (pull) Overwrite an existing destination file.
  -h, --help         Show this help.

Heads-up: cloud secrets are encrypted at rest with no read API — the
plaintext never comes back to a client, and it reaches a sandbox only for a
secret whose exposure is \`environment\`. \`env pull\` therefore exports a
SKELETON (names only), not values. \`env push\` sets values; it does not
change any secret's exposure — use \`kortix secrets delivery\` for that.
`;

export async function runEnv(argv: string[]): Promise<number> {
  const helpCode = splitHelp(argv, HELP);
  if (helpCode !== null) return helpCode;

  const sub = argv[0];
  const rest = argv.slice(1);
  let projectFlag: string | undefined;
  let hostFlag: string | undefined;
  let outFlag: string | undefined;
  let fromFlag: string | undefined;
  let force = false;
  let names = false;
  let json = false;
  let only: string[] = [];
  let exclude: string[] = [];
  try {
    projectFlag = takeFlagValue(rest, ['--project', '--workspace']);
    hostFlag = takeFlagValue(rest, ['--host']);
    outFlag = takeFlagValue(rest, ['--out', '-o']);
    fromFlag = takeFlagValue(rest, ['--from', '-f']);
    force = takeFlagBool(rest, ['--force']);
    names = takeFlagBool(rest, ['--names']);
    json = takeFlagBool(rest, ['--json']);
    only = nameList(takeFlagValues(rest, ['--only']));
    exclude = nameList(takeFlagValues(rest, ['--exclude']));
  } catch (err) {
    return fail((err as Error).message);
  }
  const ctxOpts: CtxOpts = { projectArg: projectFlag, hostArg: hostFlag };

  switch (sub) {
    case 'pull':
      return envPull(outFlag, force, ctxOpts);
    case 'push':
      return envPush(fromFlag, ctxOpts, { names, json, only, exclude });
    default:
      process.stderr.write(`${status.err(`unknown subcommand "${sub}"`)}\n\n${HELP}`);
      return 2;
  }
}

type CtxOpts = { projectArg?: string; hostArg?: string };

async function envPull(outArg: string | undefined, force: boolean, opts: CtxOpts): Promise<number> {
  const ctx = await resolveProjectContext(opts);
  if (!ctx) return 1;

  let resp: ProjectSecretsResponse;
  try {
    resp = await ctx.client.get<ProjectSecretsResponse>(
      `/workspaces/${ctx.projectId}/secrets`,
    );
  } catch (err) {
    return surfaceApiError(err);
  }

  const outPath = resolve(process.cwd(), outArg ?? '.env');
  if (!force) {
    try {
      const existing = readFileSync(outPath, 'utf8');
      if (existing.trim().length > 0) {
        process.stderr.write(
          `${status.err(`${outPath} already exists — pass --force to overwrite.`)}\n`,
        );
        return 1;
      }
    } catch {
      /* file doesn't exist — proceed */
    }
  }

  // Merge: every name in items + every required/optional → one entry.
  const names = new Set<string>();
  for (const s of resp.items) names.add(s.name);
  for (const n of resp.required) names.add(n);
  for (const n of resp.optional) names.add(n);
  const sorted = [...names].sort();

  const lines: string[] = [
    '# Generated by `kortix env pull` — fill in values locally.',
    `# Workspace: ${ctx.projectId}`,
    `# ${new Date().toISOString()}`,
    '',
  ];
  for (const name of sorted) {
    const spec = resp.required.includes(name)
      ? 'required'
      : resp.optional.includes(name)
        ? 'optional'
        : 'set in cloud';
    lines.push(`# ${spec}`);
    lines.push(`${name}=`);
  }

  writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
  process.stdout.write(
    `${status.ok(`Wrote ${C.bold}${sorted.length}${C.reset} variable name${sorted.length === 1 ? '' : 's'} to ${outPath}`)}\n`,
  );
  process.stdout.write(`${C.dim}  Values are not exported — see \`kortix env push --from .env\` to upload.${C.reset}\n`);
  return 0;
}

/** `--only A,B --only C` → [A, B, C]. */
function nameList(values: string[]): string[] {
  return values.flatMap((value) => value.split(',')).map((name) => name.trim()).filter(Boolean);
}

type PushOpts = { names: boolean; json: boolean; only: string[]; exclude: string[] };

async function envPush(fromArg: string | undefined, opts: CtxOpts, push: PushOpts): Promise<number> {
  if (!fromArg) return missing('--from <dotenv-path>');
  const srcPath = resolve(process.cwd(), fromArg);
  let raw: string;
  try {
    raw = readFileSync(srcPath, 'utf8');
  } catch (err) {
    process.stderr.write(`${status.err(`Cannot read ${srcPath}: ${(err as Error).message}`)}\n`);
    return 1;
  }

  const parsed = parseDotenv(raw);
  if (parsed.length === 0) {
    process.stderr.write(`${status.err(`No NAME=VALUE pairs found in ${srcPath}.`)}\n`);
    return 1;
  }
  // dotenvx ciphertext is not the value: uploading it would store garbage.
  const encrypted = parsed.filter((p) => p.value.startsWith('encrypted:')).map((p) => p.name);

  if (push.names) {
    const listed = parsed.map((p) => ({ name: p.name, encrypted: encrypted.includes(p.name) }));
    if (push.json) process.stdout.write(`${JSON.stringify({ file: srcPath, names: listed }, null, 2)}\n`);
    else for (const entry of listed) process.stdout.write(`${entry.name}${entry.encrypted ? `  ${C.dim}(encrypted)${C.reset}` : ''}\n`);
    return 0;
  }

  const known = new Set(parsed.map((p) => p.name));
  const unknown = [...push.only, ...push.exclude].filter((name) => !known.has(name));
  if (unknown.length > 0) {
    process.stderr.write(`${status.err(`Not in ${srcPath}: ${unknown.join(', ')}`)}\n`);
    return 1;
  }
  if (encrypted.length > 0) {
    process.stderr.write(`${status.warn(`Skipped, dotenvx-encrypted: ${encrypted.join(', ')}. Push a decrypted copy: dotenvx decrypt --stdout -f ${fromArg} > <file>.`)}\n`);
  }
  const pairs = parsed.filter(
    (p) => !encrypted.includes(p.name) && (push.only.length === 0 || push.only.includes(p.name)) && !push.exclude.includes(p.name),
  );
  if (pairs.length === 0) {
    process.stderr.write(`${status.err('No name left to upload.')}\n`);
    return 1;
  }

  const ctx = await resolveProjectContext(opts);
  if (!ctx) return 1;

  let okCount = 0;
  for (const p of pairs) {
    try {
      await ctx.client.post<ProjectSecret>(
        `/workspaces/${ctx.projectId}/secrets`,
        { name: p.name, value: p.value },
      );
      okCount += 1;
      process.stdout.write(`${status.ok(`${C.bold}${p.name}${C.reset}`)}\n`);
    } catch (err) {
      surfaceApiError(err);
      process.stderr.write(`  ${C.dim}└─ for ${p.name}${C.reset}\n`);
    }
  }
  process.stdout.write(`\n  ${C.dim}${okCount}/${pairs.length} uploaded from ${srcPath}${C.reset}\n\n`);
  return okCount === pairs.length ? 0 : 1;
}

/** Minimal dotenv parser. Supports `NAME=VALUE` and `export NAME=VALUE`,
 *  optional matching single/double quotes around the value, `#` line
 *  comments, blank lines. Skips entries with empty values. */
function parseDotenv(text: string): { name: string; value: string }[] {
  const out: { name: string; value: string }[] = [];
  for (const lineRaw of text.split(/\r?\n/)) {
    const line = lineRaw.trim();
    if (!line || line.startsWith('#')) continue;
    const stripped = line.replace(/^export\s+/, '');
    const eq = stripped.indexOf('=');
    if (eq <= 0) continue;
    const name = stripped.slice(0, eq).trim();
    let value = stripped.slice(eq + 1).trim();
    if (!value) continue;
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out.push({ name, value });
  }
  return out;
}
